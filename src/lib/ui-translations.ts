export function translateUi(lang: ContentLanguage, key: UiMessageKey): string {
  return UI_TRANSLATIONS[lang]?.[key] ?? UI_TRANSLATIONS.fr[key];
}

export function translateLibraryStatus(
  lang: ContentLanguage,
  status: LibraryStatus,
  mediaType: MediaType = "ANIME"
): string {
  const bucket = mediaType === "MANGA" ? "manga" : "anime";
  return STATUS_LABELS[lang]?.[bucket]?.[status] ?? STATUS_LABELS.fr[bucket][status];
}

export function translateGenreName(lang: ContentLanguage, genre: string): string {
  return GENRE_LABELS[lang]?.[genre] ?? genre;
}

export function translateSeasonName(
  lang: ContentLanguage,
  season: string | null | undefined
): string {
  if (!season) return "";
  const key = season.trim().toUpperCase();
  return SEASON_LABELS[lang]?.[key] ?? season;
}
