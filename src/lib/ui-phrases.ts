export const UI_PHRASES: Record<string, PhraseMap> = {
  ...UI_PHRASES_CORE,
  ...UI_PHRASES_SOCIAL,
  ...UI_PHRASES_EXTRA_A,
  ...UI_PHRASES_EXTRA_B,
};

export function translatePhrase(
  lang: ContentLanguage,
  frKey: string,
  vars?: Record<string, string | number>
): string {
  const base = lang === "fr" ? frKey : (UI_PHRASES[frKey]?.[lang] ?? frKey);
  if (!vars) return base;
  return base.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, k: string) =>
    vars[k] !== undefined ? String(vars[k]) : `{${k}}`
  );
}
